-- Portico schema on Supabase Postgres.
-- The app connects as the `portico_app` role (created separately, password in
-- .env.local as SUPABASE_DB_URL). That role owns no tables but has a permissive
-- RLS policy on every table, so anon/authenticated keys still get nothing.

create table if not exists users (
  id bigint generated by default as identity primary key,
  email text unique not null,
  name text not null default '',
  company text not null default '',
  password_hash text not null,
  role text not null default 'client' check (role in ('admin','client')),
  must_reset boolean not null default true,
  seen_intro boolean not null default false,
  status text not null default 'active' check (status in ('active','archived')),
  project_name text not null default '',
  starts_on date,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz
);

create table if not exists progress (
  user_id bigint not null references users(id) on delete cascade,
  step_id text not null,
  completed_at timestamptz not null default now(),
  primary key (user_id, step_id)
);

create table if not exists form_responses (
  user_id bigint not null references users(id) on delete cascade,
  form_id text not null,
  data jsonb not null default '{}'::jsonb,
  status text not null default 'draft' check (status in ('draft','submitted')),
  updated_at timestamptz not null default now(),
  submitted_at timestamptz,
  primary key (user_id, form_id)
);

create table if not exists deliverables (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id) on delete cascade,
  title text not null,
  summary text not null default '',
  kind text not null default 'other',
  status text not null default 'queued' check (status in ('queued','in_progress','review','approved')),
  url text not null default '',
  due_on date,
  position integer not null default 0,
  created_at timestamptz not null default now(),
  delivered_at timestamptz,
  approved_at timestamptz
);

create table if not exists files (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id) on delete cascade,
  uploaded_by bigint not null,
  uploader_role text not null default 'client' check (uploader_role in ('admin','client')),
  label text not null default '',
  category text not null default 'general',
  file_name text not null,
  stored_name text not null,
  mime text not null default '',
  size bigint not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists messages (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id) on delete cascade,
  author_id bigint not null,
  author_role text not null default 'client' check (author_role in ('admin','client')),
  author_name text not null default '',
  body text not null,
  created_at timestamptz not null default now(),
  read_by_client boolean not null default false,
  read_by_admin boolean not null default false
);

create table if not exists notes (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users(id) on delete cascade,
  author_name text not null default '',
  body text not null,
  created_at timestamptz not null default now()
);

create table if not exists activity (
  id bigint generated by default as identity primary key,
  user_id bigint references users(id) on delete cascade,
  actor_name text not null default '',
  actor_role text not null default 'client' check (actor_role in ('admin','client')),
  kind text not null,
  summary text not null,
  created_at timestamptz not null default now()
);

create table if not exists settings (
  key text primary key,
  value text not null default ''
);

create index if not exists idx_deliverables_user on deliverables(user_id);
create index if not exists idx_files_user on files(user_id);
create index if not exists idx_messages_user on messages(user_id, created_at);
create index if not exists idx_activity_created on activity(created_at);

alter table users enable row level security;
alter table progress enable row level security;
alter table form_responses enable row level security;
alter table deliverables enable row level security;
alter table files enable row level security;
alter table messages enable row level security;
alter table notes enable row level security;
alter table activity enable row level security;
alter table settings enable row level security;

do $$
declare t text;
begin
  if not exists (select 1 from pg_roles where rolname = 'portico_app') then
    raise notice 'Create the portico_app login role manually before applying this migration.';
    return;
  end if;
  foreach t in array array['users','progress','form_responses','deliverables','files','messages','notes','activity','settings'] loop
    execute format('drop policy if exists app_all on %I', t);
    execute format('create policy app_all on %I for all to portico_app using (true) with check (true)', t);
  end loop;
end $$;

grant usage on schema public to portico_app;
grant all on all tables in schema public to portico_app;
grant all on all sequences in schema public to portico_app;
alter default privileges in schema public grant all on tables to portico_app;
alter default privileges in schema public grant all on sequences to portico_app;
